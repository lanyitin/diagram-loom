use loom_core::Project;
use loom_core::edit::Edit;

/// MCP 這一層需要對專案做的事。
///
/// # 為什麼是一個 port
///
/// 這個 crate 不知道 Tauri 存在，也不知道專案存在哪裡。它只知道
/// 「有一份專案可以看，而且可以對它下 `Edit`」。
///
/// 桌面 App 用它自己的 [`History`](loom_core::history::History) 實作，
/// 所以 Agent 的每一次修改都自動進了同一條復原鏈。測試用一個最小的
/// 假實作，於是整組工具都能用 `cargo test` 驗證，不必開視窗也不必跑 server。
pub trait Workspace {
    /// 目前開著的專案。沒開專案時是 `None`——那時每個工具都該說一句人話。
    fn project(&self) -> Option<&Project>;

    /// 套用一次修改。**必須走 `History`**，否則使用者退不回來。
    fn edit(&mut self, edit: &Edit) -> Result<(), String>;
}

/// `initialize` 時交給 Agent 的規矩。
///
/// 這是它唯一會無條件讀到的說明——工具的描述要它主動看，這段不用。
/// 所以最重要的四件事寫在這裡：先 describe、一次送一批、常跑 lint、
/// 不會自動存檔。
///
/// 「一次送一批」放進來是因為它**便宜但看不出來**：一個一個送每次都會成功，
/// 沒有任何錯誤訊息會提醒 Agent 這樣很慢。等到有人發現時，
/// 已經是一個大型系統建到一半、跑了很久的時候了。
pub const INSTRUCTIONS: &str = "\
這是使用者當下開著的 diagram-loom 專案。**他可能同時開著好幾個。**

八支工具只有兩種形狀，記住這兩種就不必每次重讀說明：
  讀（describe / lint）  {scope, select, detail}
  寫（其餘四支）          {scope, items, dry_run}

`scope` 說「動哪一個專案、哪一個環境」，**環境只寫在這裡**。
只開著一個專案時 `scope.project` 可以省略；開著多個又沒給，呼叫會被擋下來
並附上一份清單——**不會替你猜一個**，因為猜錯是安靜地改到別的專案，
那比失敗糟得多。同一個名字在好幾個環境都有的時候也一樣。

不確定開著哪些就先叫 projects。一趟只動一個專案，要改三個就跑三輪。

動手之前先叫 describe——不然你會重複建立已經有的東西。它預設**不印 id**，
因為 update 與 delete 的 `target` 直接吃名字（`redis-01`、`apache-* -> f5-01`）。

**一次送一批，不要一個一個送。** 四支寫入工具都收 `items` 陣列，
你這一輪要做的事全部放進去。同一批裡後面的可以指名前面的，所以照
「系統 → 服務 → 接點定義 → 契約 → 環境 → 機器 → 連線」的順序排就好。
一趟一百個跟一趟一個花的時間差不多，而一個一個送要走一百趟。

每做完一批就叫 lint。先用 `detail: \"count\"`（只回一行數字），
不是零再展開看細節——那省下的是每一輪的整份報告。

想先看看不確定的操作會怎樣，就加 `dry_run: true`：算給你看，一個都不動。
刪除相反，它預設就只給預覽，確定了才帶 `confirm: true` 送同一組參數；
要大改結構就開 `cascade: true`，它會把連帶變成廢的東西一起掃出來。

**不會自動存檔。** 你改的東西會出現在使用者畫面上並標記為未儲存，
由他看過再決定要不要留（他也可以按 ⌘Z 退回去——一批算一步）。所以做完之後
請用人話說明你建了什麼、還剩下哪些 lint 沒解決。";
